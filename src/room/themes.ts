export function readDomTheme(): { mode: ThemeMode; palette: PaletteKey } {
  const root = document.documentElement;
  const rawPalette = root.dataset.palette;
  const palette: PaletteKey =
    rawPalette === 'moss' || rawPalette === 'wood' || rawPalette === 'mist'
      ? rawPalette
      : 'ink';
  return { mode: 'dark', palette };
}

export function getRoomTheme(palette: PaletteKey, _mode: ThemeMode = 'dark'): RoomThemeConfig {
  const variant = COSMIC_THEMES[palette] ?? COSMIC_THEMES.ink;
  return {
    mode: 'dark',
    palette,
    ...variant,
  };
}
